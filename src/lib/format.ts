/**
 * 给人看的大数字（token 额度、字符量）的中文单位格式化。
 *
 * 全站共用这一个函数。以前三处各写一份，错出两种花样：
 * - 「千万」当单位：4000 万显示成「4.00 千万」——中文没有这种写法
 * - 1000 万就换「亿」：4000 万显示成「4 亿」，整整差十倍
 *
 * 规则只有两条：满 1 亿（10^8）才用「亿」，其余 1 万以上一律用「万」。
 * 40 万 → 「40 万」，200 万 → 「200 万」，4000 万 → 「4000 万」，1.5 亿 → 「1.5 亿」。
 */
export function fmtWan(n: number): string {
  if (!Number.isFinite(n)) return String(n);
  if (n >= 100_000_000) return `${Math.round(n / 1_000_000) / 100} 亿`;
  if (n >= 10_000) return `${Math.round(n / 1_000) / 10} 万`;
  return String(n);
}
